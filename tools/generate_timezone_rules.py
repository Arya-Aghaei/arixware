"""Generate IANA-name to POSIX-rule lookup from installed TZif v2+ files.
Run with Python 3.9+; normal firmware builds use the committed lookup table.
"""
import json
from pathlib import Path
from zoneinfo import TZPATH, available_timezones

rows = []
for name in sorted(available_timezones()):
    path = next((Path(base)/name for base in TZPATH if (Path(base)/name).is_file()), None)
    if path is None:
        continue
    data = path.read_bytes()
    if not data.startswith(b'TZif') or data[4:5] not in (b'2', b'3', b'4'):
        continue
    parts = data.rsplit(b'\n', 2)
    if len(parts) == 3 and parts[-2]:
        rows.append((name, parts[-2].decode('ascii')))
assert len(rows) > 500, 'A full system tzdata installation is required'
out = Path(__file__).resolve().parents[1] / 'components/net/timezone_rules.inc'
out.write_text('/* Generated by tools/generate_timezone_rules.py from installed IANA TZif POSIX footers. */\n'
    'static const struct { const char *name; const char *rule; } TIMEZONE_RULES[] = {\n'
    + ''.join(f'    {{{json.dumps(name)}, {json.dumps(rule)}}},\n' for name, rule in rows) + '};\n')
print(f'Generated {len(rows)} timezone names')
