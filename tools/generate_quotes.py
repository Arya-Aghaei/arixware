"""Generate components/ui_core/quotes_data.inc from tools/data/arix_quotes.json.
Run: python3 tools/generate_quotes.py [quotes.json]. Normal firmware builds use the committed table.
The UI fonts only cover printable ASCII, so typographic punctuation is folded to ASCII.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FOLD = {'‘': "'", '’': "'", '“': '"', '”': '"', '–': '-', '—': '-', '…': '...', ' ': ' '}


def ascii_text(text):
    text = ' '.join(''.join(FOLD.get(c, c) for c in text).split())
    bad = sorted({c for c in text if not 32 <= ord(c) < 127})
    assert not bad, f'unsupported characters {bad} in {text!r}'
    return text


src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'tools/data/arix_quotes.json'
items = json.loads(src.read_text(encoding='utf-8'))
lines = ['/* Generated by tools/generate_quotes.py; do not edit. */']
for item in items:
    quote = ascii_text(item['quote'])
    author = ascii_text(item['attribution']) if item.get('attribution') else None
    lines.append('{ %s, %s },' % (json.dumps(quote), json.dumps(author) if author else 'NULL'))
out = ROOT / 'components/ui_core/quotes_data.inc'
out.write_text('\n'.join(lines) + '\n', encoding='ascii')
print(f'{len(items)} quotes -> {out}')
