"""Convert the supplied dream GIF to cloud-clipped, RLE RGB332 firmware frames.
Requires ffmpeg. Regenerate from the repository root with python3 tools/eyes_preview/generate_dream.py.
"""
from collections import deque
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'components/assets/gif/Counting Sheeps.gif'
OUT = ROOT / 'components/eyes_renderer/dream_frames.inc'
W, H, FPS = 190, 160, 10
# Keep the original full-bleed framing; shape the cloud with narrower sides and a fuller base.
CONTENT_SIZE, CONTENT_X, CONTENT_Y = 190, 0, -20

def ellipse(x, y, cx, cy, rx, ry):
    return ((x-cx)/rx)**2 + ((y-cy)/ry)**2 <= 1

def cloud(x, y):
    return any(ellipse(x,y,*e) for e in [(47,75,33,36), (77,49,44,42),
        (120,51,40,35), (142,76,33,35), (95,87,70,38)])

def generate(source, out, prefix, background, bubble, size=(CONTENT_SIZE, CONTENT_SIZE),
             origin=(CONTENT_X, CONTENT_Y), remove_matte=False):
    src_w, src_h = size
    content_x, content_y = origin
    raw = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(source),
        '-vf', f'fps={FPS},scale={src_w}:{src_h}', '-f', 'rawvideo', '-pix_fmt', 'rgba', '-'])
    frame_size = src_w * src_h * 4
    assert len(raw) % frame_size == 0
    mask = [cloud(x,y) for y in range(H) for x in range(W)]
    packed, offsets = bytearray(), [0]
    for start in range(0, len(raw), frame_size):
        frame = bytearray(raw[start:start+frame_size])
        # Some sources have an opaque white or off-white matte. Remove only matte
        # connected to the frame border, retaining light details inside the scene.
        if remove_matte:
            pending = deque((x,y) for y in range(src_h) for x in range(src_w)
                            if x in (0, src_w-1) or y in (0, src_h-1))
            visited = set()
            while pending:
                x,y = pending.popleft()
                if (x,y) in visited or not (0 <= x < src_w and 0 <= y < src_h):
                    continue
                visited.add((x,y))
                i = (y*src_w+x)*4
                r,g,b,a = frame[i:i+4]
                if a == 0 or (r > 240 and g > 240 and b > 235):
                    frame[i+3] = 0
                    pending.extend(((x-1,y),(x+1,y),(x,y-1),(x,y+1)))
        pixels = []
        for y in range(H):
            for x in range(W):
                if mask[y*W+x]:
                    r,g,b = background
                    sx,sy = x-content_x,y-content_y
                    if 0 <= sx < src_w and 0 <= sy < src_h:
                        pos = (sy*src_w+sx)*4
                        fr,fg,fb,a = frame[pos:pos+4]
                        r = (fr*a+r*(255-a))//255
                        g = (fg*a+g*(255-a))//255
                        b = (fb*a+b*(255-a))//255
                    value = max(1, (r & 224) | ((g >> 3) & 28) | (b >> 6))
                elif ellipse(x,y,51,126,8,7) or ellipse(x,y,37,146,4,4):
                    value = bubble
                else:
                    value = 0
                pixels.append(value)
        run, value = 0, pixels[0]
        for px in pixels:
            if px != value or run == 255:
                packed.extend((run,value)); run,value = 0,px
            run += 1
        packed.extend((run,value)); offsets.append(len(packed))

    lines = [f'/* Generated by tools/eyes_preview/generate_dream.py; source: {source.name}. */',
        '/* Animation data: Lottie Simple License; see LICENSES/Lottie-Simple-License.txt and THIRD_PARTY_NOTICES.md. */',
        f'#define {prefix.upper()}_WIDTH {W}', f'#define {prefix.upper()}_HEIGHT {H}',
        f'#define {prefix.upper()}_FRAME_MS {1000//FPS}',
        f'#define {prefix.upper()}_FRAME_COUNT {len(offsets)-1}',
        f'static const uint32_t {prefix}_offsets[] = {{', ','.join(map(str,offsets)), '};',
        f'static const uint8_t {prefix}_rle[] = {{']
    lines += [','.join(map(str,packed[i:i+32]))+',' for i in range(0,len(packed),32)]
    lines += ['};', '']
    out.write_text('\n'.join(lines))
    print(f'{source.name}: {len(offsets)-1} frames, {len(packed):,} compressed bytes')


generate(SOURCE, OUT, 'dream', (69,185,237), 0b10111011)
generate(SOURCE.with_name('Counting Sheep.gif'), OUT.with_name('dream_fence_frames.inc'),
         'dream_fence', (255,193,106), 0b11111001, remove_matte=True)

generate(SOURCE.with_name('Saving.gif'), OUT.with_name('dream_saving_frames.inc'),
         'dream_saving', (200,232,206), 0b11011110,
         size=(150,138), origin=(20,-22), remove_matte=True)
